# 为什么是"概述 + 五项"，而不是只问四项：
#   只问四项 → 干巴，领导感受不到"它看懂了"；
#   先问概述再问四项（两次调用）→ 概述最丰富（连"阴天氛围"都说得出），
#                                但耗时翻倍（12~14 s vs 6~8 s）；
#   **一次问全** → 兼得概述与细节，仍是一次调用。故取此。
#
# 为什么把"遮挡"和"清晰度"分开：
#   实测合并在一起时，模型会把"窗帘"当成"遮挡"，答"有遮挡（如窗帘）"，
#   与我们要的"被树/柱子挡住视线"不是一回事。分开问后，win02 正确答
#   "没有被树、柱子等物体挡住视线"，win06 正确答"有树木和柱子挡住视线"。
#
# ★ 已知不稳定项：**窗数**。同一张图换个问法能差两倍
#   （win06 人工标注 26，问法 C 答"二十多扇"，问法 E 答"五十扇"）。
#   所以窗数只能当量级参考，不要当精确值。楼层/开合/遮挡/清晰度相对稳定。
